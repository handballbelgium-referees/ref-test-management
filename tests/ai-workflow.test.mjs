test("preserves native skill metadata, source bodies and scope mappings", (t) => {
  const base = fixture(t);
  sync(base);
  for (const [name, scope] of Object.entries(scopes)) {
    const source = read(base, `.ai/instructions/${name}.instructions.md`);
    const copilot = read(base, `.github/instructions/${name}.instructions.md`);
    const claude = read(base, `.claude/rules/${name}.md`);
    assert.equal(header(source), `applyTo: "${scope}"`);
    assert.equal(header(copilot), header(source));
    assert.equal(header(claude), `paths: "${scope}"`);
    assert.equal(withoutMarker(copilot), source);
    assert.equal(withoutMarker(claude).replace("paths:", "applyTo:"), source);
    assert.match(read(base, "AGENTS.md"), new RegExp(scope.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")));
  }
  for (const [name, template] of [["audit", "template.md"], ["deliver", "plan-template.md"]]) {
    for (const file of ["SKILL.md", template]) {
      const source = read(base, `.agents/skills/${name}/${file}`);
      const generated = read(base, `.claude/skills/${name}/${file}`);
      assert.equal(withoutMarker(generated), source);
      if (file === "SKILL.md") {
        assert.equal(header(generated), header(source));
        assert.match(header(source), new RegExp(`^name: ${name}$`, "m"));
        assert.match(header(source), /^description: >-\n  \S/m);
        assert.ok(generated.indexOf(owner) > generated.indexOf("\n---\n"));
      }
    }
  }
  const issue = read(base, ".github/ISSUE_TEMPLATE/work-item.md");
  assert.equal(header(issue), 'name: Work item\nabout: Request a feature, report a defect, or describe approved follow-up work.\ntitle: ""\nlabels: ""\nassignees: ""');
  assert.equal(withoutMarker(issue.slice(issue.indexOf("\n---\n") + 5)).trimStart(), read(base, ".ai/templates/issue.md"));
  assert.equal(withoutMarker(read(base, ".github/pull_request_template.md")), read(base, ".ai/templates/pull-request.md"));
});

test("copies nested resources byte-for-byte and updates owned resources after source edits", (t) => {
  const base = fixture(t);
  const binary = Buffer.from([0, 255, 13, 10, 128, 1]);
  write(base, ".agents/skills/audit/resources/sample.bin", binary);
  write(base, ".agents/skills/audit/resources/example.txt", "keep\r\nbytes\r\n");
  write(base, ".agents/skills/audit/resources/example.md", "# Resource\r\n\r\n[Report](../template.md)\r\n");
  assert.equal(sync(base).total, 19);
  const destination = ".claude/skills/audit/resources/sample.bin";
  assert.deepEqual(readFileSync(path.join(base, destination)), binary);
  assert.equal(readFileSync(path.join(base, ".claude/skills/audit/resources/example.txt"), "utf8"), "keep\r\nbytes\r\n");
  assert.equal(withoutMarker(read(base, ".claude/skills/audit/resources/example.md")), "# Resource\n\n[Report](../template.md)\n");
  const manifest = JSON.parse(read(base, ".claude/skills/audit/.managed-by-sync.json"));
  assert.deepEqual(manifest, {
    generatedBy: owner,
    resources: {
      "resources/example.txt": digest(Buffer.from("keep\r\nbytes\r\n")),
      "resources/sample.bin": digest(binary),
    },
  });
  write(base, ".agents/skills/audit/resources/sample.bin", Buffer.from([2, 3]));
  assert.equal(sync(base).written, 2);
  assert.deepEqual(readFileSync(path.join(base, destination)), Buffer.from([2, 3]));
  assert.deepEqual(sync(base, { check: true }), { issues: [], written: 0, total: 19 });
});

