function snapshotFile(file, expected) {
  const descriptor = openSync(file, constants.O_RDONLY | (constants.O_NOFOLLOW ?? 0));
  try {
    const stat = fstatSync(descriptor);
    assert.ok(stat.isFile() && stat.dev === expected.dev && stat.ino === expected.ino,
      "snapshot file changed after lstat");
    return {
      mode: stat.mode,
      mtime: stat.mtimeMs,
      content: readFileSync(descriptor).toString("base64"),
    };
  } finally {
    closeSync(descriptor);
  }
}

function snapshot(base) {
  const result = {};
  function visit(directory) {
    for (const name of readdirSync(directory).sort()) {
      const file = path.join(directory, name);
      const stat = lstatSync(file);
      const relative = path.relative(base, file).split(path.sep).join("/");
      result[relative] = stat.isFile() ? snapshotFile(file, stat) : {
        mode: stat.mode,
        mtime: stat.mtimeMs,
        content: stat.isSymbolicLink() ? readlinkSync(file) : null,
      };
      if (stat.isDirectory() && !stat.isSymbolicLink()) visit(file);
    }
  }
  visit(base);
  return result;
}

function header(content) {
  const match = /^---\n([\s\S]+?)\n---\n/.exec(content);
  assert.ok(match, "native YAML frontmatter must be first");
  return match[1];
}

function withoutMarker(content) {
  return content.replace(/<!-- GENERATED by \.ai\/scripts\/sync\.mjs from [^\n]+ -->\n\n/, "");
}

function cli(base, args, cwd = base, script = "sync.mjs") {
  const result = spawnSync(process.execPath, [path.join(base, ".ai", "scripts", script), ...args], {
    cwd, encoding: "utf8", timeout: 15_000,
  });
  assert.ifError(result.error);
  assert.equal(result.signal, null);
  return result;
}

