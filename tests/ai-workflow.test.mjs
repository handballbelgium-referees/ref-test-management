function checkLinks(base, file, content = read(base, file)) {
  const links = [...content.matchAll(/\[[^\]\n]+\]\(([^)\s]+)\)/g)].map((match) => match[1]);
  const definitions = new Map([...content.matchAll(/^\[([^\]]+)\]:\s+(\S+)/gm)].map((match) => [match[1], match[2]]));
  for (const match of content.matchAll(/\[[^\]\n]+\]\[([^\]]+)\]/g)) {
    assert.ok(definitions.has(match[1]), `${file}: missing reference ${match[1]}`);
  }
  links.push(...definitions.values());
  for (const link of links) {
    if (/^(https?:|mailto:)/.test(link)) continue;
    const [relative, anchor] = link.split("#");
    const destination = path.resolve(path.dirname(path.join(base, file)), decodeURIComponent(relative));
    const within = path.relative(base, destination);
    assert.ok(!within.startsWith("..") && !path.isAbsolute(within), `${file}: escaped link ${link}`);
    assert.ok(existsSync(destination), `${file}: broken link ${link}`);
    if (anchor) {
      const headings = [...readFileSync(destination, "utf8").matchAll(/^#{1,6} (.+)$/gm)]
        .map((match) => match[1].toLowerCase().replace(/[^\p{L}\p{N}_\s-]/gu, "").trim().replace(/\s/g, "-"));
      assert.ok(headings.includes(anchor), `${file}: missing heading ${link}`);
    }
  }
}

